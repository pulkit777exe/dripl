import { z } from 'zod';

export const PointSchema = z.object({
  x: z.number().finite(),
  y: z.number().finite(),
});

export const BindingSchema = z
  .object({
    elementId: z.string(),
    fixedPoint: PointSchema,
    mode: z.enum(['inside', 'orbit']),
  })
  .optional();

export const TextAlignSchema = z.enum(['left', 'center', 'right']);

const ImageSourceSchema = z
  .string()
  .max(2_000_000)
  .refine(value => {
    if (value.startsWith('/')) return !value.startsWith('//');
    if (value.startsWith('data:')) {
      return /^data:image\/(?:png|jpe?g|gif|webp);base64,/i.test(value);
    }
    try {
      const protocol = new URL(value).protocol;
      return protocol === 'https:' || protocol === 'http:';
    } catch {
      return false;
    }
  }, 'Image source must be an HTTP(S), local, or raster data URL');

/**
 * Schemes that turn an element hyperlink into script execution when the link
 * is opened or rendered as an `href`.
 *
 * Matched case-insensitively after leading whitespace: `new URL` and browsers
 * both ignore that whitespace, so `   JavaScript:…` executes exactly like
 * `javascript:…`. `data:` is narrowed to `data:text/html` — the executable
 * HTML carrier — so inert payloads keep parsing; anything executable is
 * garbage input and is refused at the boundary.
 */
const UNSAFE_LINK_SCHEME = /^\s*(?:javascript|vbscript)\s*:/i;
const UNSAFE_LINK_DATA_HTML = /^\s*data\s*:\s*text\/html/i;

function isSafeElementLink(value: string): boolean {
  return !UNSAFE_LINK_SCHEME.test(value) && !UNSAFE_LINK_DATA_HTML.test(value);
}

export const ElementTypeSchema = z.enum([
  'rectangle',
  'ellipse',
  'path',
  'text',
  'image',
  'line',
  'arrow',
  // Specialized element types supported by the editor
  'diamond',
  'freedraw',
  'frame',
  'embed',
]);

export const BaseElementSchema = z.object({
  // Element IDs are generated by several supported clients (and older
  // persisted scenes may use non-UUID IDs), so validate a bounded opaque ID
  // rather than silently dropping a whole scene during import/sync.
  id: z.string().min(1).max(100),
  type: ElementTypeSchema,
  x: z.number().finite().min(-100000).max(100000),
  y: z.number().finite().min(-100000).max(100000),
  width: z.number().finite().min(0).max(50000),
  height: z.number().finite().min(0).max(50000),
  angle: z.number().default(0),
  strokeColor: z.string().max(100).default('#000000'),
  fillColor: z.string().max(100).default('transparent'),
  backgroundColor: z.string().max(100).default('transparent'),
  strokeWidth: z.number().min(0).max(100).default(2),
  opacity: z.number().min(0).max(1).default(1),
  roughness: z.number().min(0).max(2).default(1),
  locked: z.boolean().default(false),
  // Existing fields preserved
  isDeleted: z.boolean().optional(),
  version: z.number().int().nonnegative().optional(),
  versionNonce: z.number().int().nonnegative().optional(),
  updated: z.number().int().nonnegative().optional(),
  createdAt: z.number().int().nonnegative().optional(),
  updatedAt: z.number().int().nonnegative().optional(),
  strokeStyle: z.enum(['solid', 'dashed', 'dotted']).optional(),
  fillStyle: z
    .enum(['hachure', 'solid', 'zigzag', 'cross-hatch', 'dots', 'dashed', 'zigzag-line'])
    .optional(),
  seed: z.number().optional(),
  groupId: z.string().max(100).optional(),
  zIndex: z.number().int().optional(),
  fractionalIndex: z.string().min(1).max(256).optional(),
  rotation: z.number().finite().min(-360).max(360).optional(),
  flipHorizontal: z.union([z.literal(-1), z.literal(1)]).optional(),
  flipVertical: z.union([z.literal(-1), z.literal(1)]).optional(),
  labelId: z.string().max(100).optional(),
  containerId: z.string().max(100).optional(),
  boundElementId: z.string().max(100).optional(),
  /** Hyperlink attached to the element. Executable schemes are refused at the
   * schema boundary (the UI open-button and the export normaliser gate on top
   * of this); every other shape — http(s), relative, fragment, bare host —
   * parses exactly as before. */
  link: z
    .string()
    .max(2000)
    .refine(isSafeElementLink, 'Link must not use an executable scheme')
    .optional(),
  boundElements: z
    .array(
      z.object({
        id: z.string().min(1).max(100),
        type: z.enum(['arrow', 'text']),
      })
    )
    .max(1000)
    .optional(),
});

export const RectangleElementSchema = BaseElementSchema.extend({
  type: z.literal('rectangle'),
});

export const EllipseElementSchema = BaseElementSchema.extend({
  type: z.literal('ellipse'),
});

export const PathElementSchema = BaseElementSchema.extend({
  type: z.literal('path'),
  points: z.array(PointSchema).min(1).max(20000),
});

const LinearStyleShape = {
  arrowStyle: z.enum(['straight', 'curved', 'elbow']).optional(),
  arrowHeads: z
    .object({
      start: z.enum(['triangle', 'dot', 'bar', 'diamond', 'none']).optional(),
      end: z.enum(['triangle', 'dot', 'bar', 'diamond', 'none']).optional(),
    })
    .optional(),
  startBinding: BindingSchema,
  endBinding: BindingSchema,
};

export const LineElementSchema = BaseElementSchema.extend({
  type: z.literal('line'),
  points: z.array(PointSchema).min(2).max(10000),
  ...LinearStyleShape,
});

/**
 * Move-only delta: an element whose sole mutation is translation. Carries
 * the new origin plus the freshness markers, so receivers merge it onto
 * their own copy instead of receiving the whole record — a drag of a
 * 2000-point stroke moves ~100 bytes per flush instead of ~100KB.
 * Version and nonce are required (the freshness fence cannot run without
 * them); legacy unversioned elements always travel as full records.
 */
export const MovedElementSchema = z.object({
  id: z.string().min(1).max(100),
  x: z.number().finite().min(-100000).max(100000),
  y: z.number().finite().min(-100000).max(100000),
  version: z.number().int().nonnegative(),
  versionNonce: z.number().int().nonnegative(),
});

export type MovedElement = z.infer<typeof MovedElementSchema>;

export const ArrowElementSchema = BaseElementSchema.extend({
  type: z.literal('arrow'),
  points: z.array(PointSchema).min(2).max(10000),
  ...LinearStyleShape,
});

export const TextElementSchema = BaseElementSchema.extend({
  type: z.literal('text'),
  text: z.string().max(10000),
  originalText: z.string().max(10000).optional(),
  fontSize: z.number().finite().min(1).max(500).default(20),
  fontFamily: z.string().max(100).default('Caveat'),
  textAlign: TextAlignSchema.default('left'),
  verticalAlign: z.enum(['top', 'middle', 'bottom']).optional(),
  boundElementId: z.string().max(100).optional(),
  containerId: z.string().max(100).optional(),
});

export const ImageElementSchema = BaseElementSchema.extend({
  type: z.literal('image'),
  dataUrl: ImageSourceSchema.optional(),
  src: ImageSourceSchema.optional(),
  naturalWidth: z.number().finite().positive().optional(),
  naturalHeight: z.number().finite().positive().optional(),
});

const DiamondElementSchema = BaseElementSchema.extend({
  type: z.literal('diamond'),
});

const FreeDrawElementSchema = BaseElementSchema.extend({
  type: z.literal('freedraw'),
  points: z.array(PointSchema).min(1).max(20000),
  brushSize: z.number().finite().min(0).max(100).optional(),
  pressureValues: z.array(z.number().finite().min(0).max(1)).max(20000).optional(),
  widths: z.array(z.number().finite().min(0).max(100)).max(20000).optional(),
});

const FrameElementSchema = BaseElementSchema.extend({
  type: z.literal('frame'),
  title: z.string().max(500).optional(),
  padding: z.number().finite().min(0).max(10000).optional(),
});

const EmbedElementSchema = BaseElementSchema.extend({
  type: z.literal('embed'),
  url: z
    .string()
    .url()
    .max(2048)
    .refine(value => /^https?:$/i.test(new URL(value).protocol), 'Embed URL must use HTTP(S)'),
  title: z.string().max(500).optional(),
  cachedPreview: z.string().max(2_000_000).optional(),
});

export const DriplElementSchema = z.discriminatedUnion('type', [
  RectangleElementSchema,
  EllipseElementSchema,
  PathElementSchema,
  TextElementSchema,
  ImageElementSchema,
  LineElementSchema,
  ArrowElementSchema,
  DiamondElementSchema,
  FreeDrawElementSchema,
  FrameElementSchema,
  EmbedElementSchema,
]);

export const ElementSchema = DriplElementSchema;
export const CanvasContentSchema = z.array(DriplElementSchema);

